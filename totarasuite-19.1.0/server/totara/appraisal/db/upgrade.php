/**
 * Local database upgrade script
 *
 * @param   integer $oldversion Current (pre-upgrade) local db version timestamp
 * @return  boolean $result
 */
function xmldb_totara_appraisal_upgrade($oldversion) {
    global $CFG, $DB;

    $dbman = $DB->get_manager();

    if ($oldversion < 2023062200) {
        // Queue the closing of active appraisals.
        \core\task\manager::queue_adhoc_task(new \totara_appraisal\task\close_appraisals_task());

        upgrade_plugin_savepoint(true, 2023062200, 'totara', 'appraisal');
    }

    return true;
}
